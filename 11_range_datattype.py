# Range: 

    # It is a sequence of numbers
    # range is immutable
    # range is memory friendly
    # range is designed to generate sequence of numbers on fly (runtime)


# How to create a range:

    # range(start, end, step)

# r1 = range(5)   # start = 0 default, end = 5, step = 1
# print(r1)   #range(0, 5)
# print(type(r1))  #<class 'range'>
# print(list(r1))  #[0, 1, 2, 3, 4]

